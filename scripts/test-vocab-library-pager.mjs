#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";

const root=new URL("../static/tien-ich/hoc-tieng-viet-han-anh/",import.meta.url);
const helper=fs.readFileSync(new URL("vocab-order.js",root),"utf8");
const sandbox={window:{}};
vm.runInNewContext(helper,sandbox,{filename:"vocab-order.js"});
const {newestFirst,containsNewRows,contentChanged}=sandbox.window.BNVocabOrdering;
const row=(n,sheet="vocab")=>({sheetId:sheet,tabTitle:"Sheet1",row:n,vi:"word-"+n,ko:"word-"+n,en:"word-"+n,id:sheet+n});
const original=Array.from({length:17},(_,i)=>row(i+2));
const sorted=newestFirst(original);
assert.equal(sorted[0].row,18,"show latest appended row first");
assert.equal(sorted[1].row,17);
assert.equal(sorted.at(-1).row,2);
const pages=Array.from({length:Math.ceil(sorted.length/3)},(_,i)=>sorted.slice(i*3,(i+1)*3));
assert.equal(pages.length,6,"17 terms with 3 per page yields 6 pages");
assert.equal(pages[0].length,3);
assert.equal(pages.at(-1).length,2);
assert.equal(JSON.stringify(original),JSON.stringify(Array.from({length:17},(_,i)=>row(i+2))),"no mutation");
const appended=[...original,row(19)];
assert.equal(containsNewRows(appended,original),true,"detect newly appended live row");
assert.equal(newestFirst(appended)[0].row,19);
assert.equal(containsNewRows([...original].reverse(),original),false,"reordering is not a new row");
assert.equal(contentChanged(original,original),false,"unchanged polling should not re-render");
assert.equal(contentChanged(appended,original),true);
const edited=original.map(x=>x.row===5?{...x,en:"changed"}:x);
assert.equal(containsNewRows(edited,original),false,"editing a row should not reset pagination");
assert.equal(contentChanged(edited,original),true,"edited row still updates");
const cross=[{...row(2,"a"),createdAt:"2026-10-01T00:00:00Z"},{...row(3,"b"),createdAt:"2026-11-01T00:00:00Z"}];
assert.equal(newestFirst(cross)[0].sheetId,"b","use genuine timestamps across sheets when available");
const index=fs.readFileSync(new URL("index.html",root),"utf8");
const study=fs.readFileSync(new URL("study.js",root),"utf8");
const css=fs.readFileSync(new URL("study.css",root),"utf8");
assert.ok(index.includes('class="panel vocab-library"'));
assert.ok(index.indexOf('src="vocab-order.js"')<index.indexOf('src="study.js"'));
assert.match(study,/\blimit=3;/);
assert.match(study,/if\(changed\)select\(newer\)/);
assert.match(css,/\.vocab-library\s*\{/);
console.log("PASS: newest-first, 3-per-page, new-row refresh, stable browsing, highlighted panel");
